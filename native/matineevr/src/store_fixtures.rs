use crate::store_geometry::{Vertex, box_mesh};

pub fn shop(v: &mut Vec<Vertex>) {
    let blue = [0.035, 0.10, 0.22];
    let gold = [0.85, 0.56, 0.12];
    let wood = [0.22, 0.12, 0.045];
    for x in -6..6 {
        for z in -4..9 {
            let tone = if (x + z) % 2 == 0 { 0.16 } else { 0.12 };
            box_mesh(v, [x as f32 + 0.5, -1.50, z as f32 + 0.5],
                [0.98, 0.025, 0.98], [tone, tone * 0.9, tone * 0.7]);
        }
    }
    for (p, size) in [([0.0, 0.25, -4.0], [12.0, 3.5, 0.15]),
        ([-6.0, 0.25, 2.5], [0.15, 3.5, 13.0]),
        ([6.0, 0.25, 2.5], [0.15, 3.5, 13.0]),
        ([0.0, 0.25, 9.0], [12.0, 3.5, 0.15])] {
        box_mesh(v, p, size, blue);
        box_mesh(v, [p[0], 1.35, p[2]], [size[0], 0.18, size[2]], gold);
    }
    box_mesh(v, [0.0, 2.0, 2.5], [12.0, 0.10, 13.0], [0.045, 0.055, 0.08]);
    box_mesh(v, [0.0, -1.475, 0.2], [3.6, 0.015, 3.4], blue);
    for x in [-1.75, 1.75] {
        box_mesh(v, [x, -1.46, 0.2], [0.045, 0.015, 3.4], gold);
    }
    for z in [-1.45, 1.85] {
        box_mesh(v, [0.0, -1.46, z], [3.5, 0.015, 0.045], gold);
    }
    for x in [-4.3, 4.3] {
        for z in [0.5, 4.0] {
            box_mesh(v, [x, -0.65, z], [1.15, 1.65, 2.5], blue);
            for y in [-1.15, -0.65, -0.15, 0.25] {
                box_mesh(v, [x, y, z], [1.35, 0.055, 2.65], wood);
                for side in [-1.0, 1.0] {
                    box_mesh(v, [x + side * 0.66, y + 0.035, z],
                        [0.035, 0.025, 2.65], gold);
                }
            }
        }
    }
    box_mesh(v, [0.0, -0.82, 6.2], [4.2, 1.35, 1.1], blue);
    box_mesh(v, [0.0, -0.12, 6.2], [4.4, 0.08, 1.3], wood);
    box_mesh(v, [0.0, -0.4, 5.63], [3.8, 0.10, 0.025], gold);
    box_mesh(v, [1.1, 0.12, 6.15], [0.50, 0.40, 0.12], [0.08, 0.09, 0.10]);
    box_mesh(v, [1.1, 0.12, 6.08], [0.42, 0.30, 0.015], [0.12, 0.42, 0.50]);
    box_mesh(v, [1.1, -0.04, 6.15], [0.14, 0.20, 0.14], [0.08, 0.09, 0.10]);
    for x in [-4.0, 0.0, 4.0] {
        for z in [-1.5, 2.5, 6.5] {
            box_mesh(v, [x, 1.91, z], [1.5, 0.055, 0.35], [0.82, 0.87, 0.96]);
        }
    }
    for x in [-3.5, 3.5] {
        box_mesh(v, [x, 0.15, -3.9], [1.2, 1.8, 0.06], gold);
        box_mesh(v, [x, 0.15, -3.85], [1.05, 1.65, 0.05], [0.07, 0.20, 0.34]);
    }
    box_mesh(v, [0.0, -0.15, 8.9], [1.8, 2.7, 0.08], [0.08, 0.24, 0.34]);
    box_mesh(v, [0.7, -0.15, 8.83], [0.04, 0.35, 0.08], gold);
}
