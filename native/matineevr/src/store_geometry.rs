pub fn bank_pose(bank: usize) -> ([f32; 3], f32) {
    match bank { 1 => ([5.145, -0.445, 0.0], -std::f32::consts::FRAC_PI_2),
        2 => ([-5.145, -0.445, 0.0], std::f32::consts::FRAC_PI_2),
        _ => ([0.0, -0.445, -4.345], 0.0) }
}

pub fn box_mesh(vertices: &mut Vec<Vertex>, center: [f32; 3], size: [f32; 3], color: [f32; 3]) {
    for axis in 0..3 {
        let a = (axis + 1) % 3;
        let b = (axis + 2) % 3;
        for sign in [-1.0, 1.0] {
            let mut normal = [0.0; 4]; normal[axis] = sign;
            let points: [_; 4] = std::array::from_fn(|i| {
                let mut p = [center[0], center[1], center[2], 1.0];
                p[axis] += sign * size[axis] / 2.0;
                p[a] += [-1.0, 1.0, 1.0, -1.0][i] * size[a] / 2.0;
                p[b] += [-1.0, -1.0, 1.0, 1.0][i] * size[b] / 2.0;
                p
            });
            for i in [0, 1, 2, 0, 2, 3] {
                vertices.push([points[i], normal, [color[0], color[1], color[2], 1.0]]);
            }
        }
    }
}

pub fn room() -> Vec<Vertex> {
    let mut v = Vec::new();
    crate::store_fixtures::shop(&mut v);
    crate::store_signs::signs(&mut v);
    crate::store_props::append(&mut v);
    let black = [0.035, 0.035, 0.04];
    for bank in 0..3 {
        let (p, _) = bank_pose(bank);
        let map = |x: f32, y: f32, z: f32| if bank == 0 { [x, y, -4.45 + z] }
            else { [if bank == 1 { 5.25 - z } else { -5.25 + z }, y, x] };
        let dims = |w: f32, h: f32, d: f32| if bank == 0 { [w,h,d] } else { [d,h,w] };
        box_mesh(&mut v, map(0.0, -0.49, -0.07), dims(1.84, 1.65, 0.08), black);
        for y in [-1.07, -0.665, -0.26, 0.145] {
            box_mesh(&mut v, map(0.0, y, 0.05), dims(1.84, 0.035, 0.22), black);
            box_mesh(&mut v, map(0.0, y + 0.027, 0.17), dims(1.84, 0.04, 0.022), [0.08,0.08,0.09]);
        }
        for x in [-0.91, 0.91] {
            box_mesh(&mut v, map(x, -0.49, 0.0), dims(0.035, 1.65, 0.25), black);
        }
        let _ = p;
    }
    for (i, center) in CARDS.into_iter().enumerate() {
        box_mesh(&mut v, center, if i < 18 { [0.222,0.374,0.045] }
            else { [0.045,0.374,0.222] }, black);
    }
    v
}

pub fn beam(v: &mut Vec<Vertex>, origin: [f32; 3], direction: [f32; 3], distance: f32, color: [f32; 3]) {
    for axis in [0, 1] {
        let mut points = [[0.0; 4]; 4];
        for (i, p) in points.iter_mut().enumerate() {
            let t = if i < 2 { 0.08 } else { distance };
            *p = [origin[0] + direction[0] * t, origin[1] + direction[1] * t,
                origin[2] + direction[2] * t, 1.0];
            p[axis] += if i % 2 == 0 { -0.004 } else { 0.004 };
        }
        for i in [0, 1, 2, 1, 3, 2] {
            v.push([points[i], [0.0, 0.0, 1.0, 0.0], [color[0], color[1], color[2], 1.0]]);
        }
    }
}
