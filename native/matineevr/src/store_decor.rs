use crate::store_geometry::{Vertex, box_mesh};

pub fn append(v: &mut Vec<Vertex>) {
    let trim = [0.085, 0.075, 0.09];
    for x in [crate::store_bounds::LEFT+0.11, crate::store_bounds::RIGHT-0.11] {
        box_mesh(v,[x,-1.37,10.0],[0.05,0.22,29.8],trim);
        box_mesh(v,[x,0.60,10.0],[0.06,0.065,29.8],[0.57,0.39,0.16]);
        for z in [-3.0,2.0,7.0,12.0,17.0,22.0] {
            box_mesh(v,[x,-0.30,z],[0.10,2.35,0.18],[0.045,0.075,0.12]);
        }
    }
    for x in [-12.0,-4.0,4.0,12.0,20.0,26.0] {
        for z in [0.0,8.0,16.0,22.0] {
            box_mesh(v,[x,1.968,z],[0.75,0.025,0.48],[0.18,0.19,0.20]);
            for offset in -5..6 {
                box_mesh(v,[x+offset as f32*0.06,1.95,z],[0.024,0.018,0.42],[0.34,0.35,0.34]);
            }
        }
    }
    let furniture_start = v.len();
    box_mesh(v,[-8.8,-1.0,12.3],[1.05,0.32,2.8],[0.18,0.075,0.12]);
    box_mesh(v,[-9.20,-0.70,12.3],[0.18,0.62,2.8],[0.23,0.10,0.16]);
    for z in [11.2,13.4] {
        for x in [-9.15,-8.45] { box_mesh(v,[x,-1.33,z],[0.08,0.34,0.08],trim); }
    }
    for z in [11.35,12.3,13.25] {
        box_mesh(v,[-8.68,-0.827,z],[0.78,0.014,0.012],[0.10,0.045,0.08]);
    }
    for x in [-3.8,3.8] {
        box_mesh(v,[x,-0.97,14.3],[0.86,1.0,0.65],[0.19,0.15,0.12]);
        box_mesh(v,[x,-0.43,14.3],[0.98,0.08,0.76],[0.39,0.31,0.22]);
        for i in 0..4 {
            let y = -0.365+i as f32*0.045;
            box_mesh(v,[x+0.12,y,14.3],[0.31,0.04,0.18],[0.045,0.045,0.055]);
            box_mesh(v,[x+0.12,y+0.022,14.3],[0.21,0.006,0.09],[0.59,0.52,0.39]);
        }
    }
    for vertex in &mut v[furniture_start..] {
        vertex[0][2] += 8.0;
        if vertex[0][0] < -8.0 { vertex[0][0] -= 6.0; }
        else if vertex[0][0] > 8.0 { vertex[0][0] -= 21.6; }
    }
    kiosk(v);
}

fn kiosk(v: &mut Vec<Vertex>) {
    let start=v.len();
    box_mesh(v,[8.8,0.04,12.40],[0.62,0.46,0.46],[0.57,0.53,0.43]);
    box_mesh(v,[8.8,0.05,12.155],[0.50,0.33,0.026],[0.025,0.075,0.07]);
    for i in 0..4 {
        box_mesh(v,[8.8,-0.18+i as f32*0.055,12.133],[0.23,0.016,0.008],[0.08,0.19,0.14]);
    }
    box_mesh(v,[8.8,-0.17,11.98],[0.53,0.05,0.23],[0.32,0.31,0.28]);
    for row in 0..3 {
        for key in 0..10 {
            box_mesh(v,[8.58+key as f32*0.047,-0.137,11.91+row as f32*0.055],
                [0.035,0.012,0.035],[0.67,0.63,0.54]);
        }
    }
    for vertex in &mut v[start..] {
        vertex[0][0]+=0.85-8.8;
        vertex[0][1]+=-0.421+0.19;
        vertex[0][2]+=23.25-12.2;
    }
}
