use crate::store_geometry::{Vertex,box_mesh};

pub const STATIONS: [[f32;2];3] = [[11.5,8.0],[11.5,12.0],[11.5,16.0]];
pub const CEILING_TVS: [[f32;3];4] = [[-10.0,1.27,4.0],[-5.5,1.27,9.0],[-1.0,1.27,14.0],[3.5,1.27,19.0]];

pub fn obstacles() -> Vec<[f32;4]> {
    let mut result: Vec<_> = STATIONS.iter().map(|[x,z]| [x-0.85,x+0.85,z-0.65,z+0.65]).collect();
    for z in [6.5,10.5,14.5] { result.push([14.1,15.3,z-1.5,z+1.5]); }
    result
}

pub fn append(v: &mut Vec<Vertex>) {
    for [x,z] in STATIONS {
        box_mesh(v,[x,-1.01,z],[1.6,0.92,1.1],[0.15,0.12,0.10]);
        box_mesh(v,[x,-0.51,z],[1.72,0.08,1.22],[0.29,0.24,0.19]);
        box_mesh(v,[x,-0.42,z-0.39],[0.40,0.06,0.19],[0.17,0.17,0.19]);
        for side in [-1.0,1.0] {
            box_mesh(v,[x+side*0.48,-0.42,z-0.39],[0.21,0.045,0.12],[0.38,0.38,0.41]);
            box_mesh(v,[x+side*0.48,-0.392,z-0.39],[0.045,0.018,0.045],[0.045,0.045,0.055]);
        }
    }
    for z in [6.5,10.5,14.5] {
        box_mesh(v,[14.7,-0.58,z],[0.6,1.82,3.0],[0.04,0.04,0.05]);
        for y in [-1.22,-0.80,-0.38,0.04] {
            box_mesh(v,[14.55,y,z],[0.87,0.045,3.0],[0.08,0.08,0.09]);
            for slot in 0..9 {
                let p = [14.40,y+0.17,z-1.2+slot as f32*0.30];
                let disc = slot%2 == 0;
                box_mesh(v,p,if disc { [0.18,0.28,0.035] } else { [0.16,0.19,0.075] },
                    if disc { [0.17,0.17,0.19] } else { [0.37,0.37,0.39] });
                box_mesh(v,[p[0]-0.096,p[1],p[2]],[0.01,0.12,0.023],
                    [[0.19,0.34,0.39],[0.40,0.16,0.20],[0.31,0.23,0.40]][slot%3]);
            }
        }
    }
    for p in CEILING_TVS {
        box_mesh(v,[p[0],1.82,p[2]+0.15],[0.07,0.40,0.07],[0.10,0.10,0.12]);
        box_mesh(v,[p[0],1.58,p[2]],[1.0,0.05,0.66],[0.10,0.10,0.12]);
    }
}
